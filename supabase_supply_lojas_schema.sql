CREATE TABLE IF NOT EXISTS public.supply_lojas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codfil INTEGER DEFAULT 994,                      -- Filial de origem (CD)
  codigo_produto VARCHAR(50),                      -- Código interno do produto
  codproddf VARCHAR(50),                          -- Código de barras / DF
  descricao VARCHAR(255),                         -- Descrição do produto
  
  -- Métricas do CD 994
  fisico_994 NUMERIC(15, 2) DEFAULT 0,
  tecnico_994 NUMERIC(15, 2) DEFAULT 0,
  resfis_994 NUMERIC(15, 2) DEFAULT 0,
  reslog_994 NUMERIC(15, 2) DEFAULT 0,
  logico_994 NUMERIC(15, 2) DEFAULT 0,
  transito_994 NUMERIC(15, 2) DEFAULT 0,
  estoque_994 NUMERIC(15, 2) DEFAULT 0,
  
  -- Informações da Filial / Loja Destino
  filial INTEGER,                                 -- Código da loja de destino
  fisico NUMERIC(15, 2) DEFAULT 0,
  tecnico NUMERIC(15, 2) DEFAULT 0,
  resfis NUMERIC(15, 2) DEFAULT 0,
  reslog NUMERIC(15, 2) DEFAULT 0,
  logico NUMERIC(15, 2) DEFAULT 0,
  transito NUMERIC(15, 2) DEFAULT 0,
  estoque_loja NUMERIC(15, 2) DEFAULT 0,
  
  -- Informações Financeiras e Categorização
  cmup NUMERIC(15, 4) DEFAULT 0,                  -- Custo médio unitário
  valor_estoque_994 NUMERIC(15, 2) DEFAULT 0,     -- Valor do estoque no CD
  status_estoque VARCHAR(100),                    -- Ex: LOJA SEM FISICO
  desclinha VARCHAR(150),                         -- Ex: BR - BRINQUEDOS
  
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Índices estratégicos para pesquisas rápidas, agregações do Dashboard e paginação
CREATE INDEX IF NOT EXISTS idx_supply_filial ON public.supply_lojas(filial);
CREATE INDEX IF NOT EXISTS idx_supply_codigo_produto ON public.supply_lojas(codigo_produto);
CREATE INDEX IF NOT EXISTS idx_supply_status_estoque ON public.supply_lojas(status_estoque);
CREATE INDEX IF NOT EXISTS idx_supply_desclinha ON public.supply_lojas(desclinha);
CREATE INDEX IF NOT EXISTS idx_supply_codproddf ON public.supply_lojas(codproddf);

-- Habilitar RLS (Row Level Security) e permitir leitura e escrita públicas
ALTER TABLE public.supply_lojas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura publica de supply_lojas" ON public.supply_lojas;
CREATE POLICY "Permitir leitura publica de supply_lojas"
  ON public.supply_lojas FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Permitir insercao e atualizacao publica de supply_lojas" ON public.supply_lojas;
CREATE POLICY "Permitir insercao e atualizacao publica de supply_lojas"
  ON public.supply_lojas FOR ALL
  USING (true)
  WITH CHECK (true);

