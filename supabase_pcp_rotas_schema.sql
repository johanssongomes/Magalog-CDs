CREATE TABLE IF NOT EXISTS public.pcp_parametros_rotas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filial_rota VARCHAR(150) UNIQUE NOT NULL,
  destino VARCHAR(255) NOT NULL,
  regiao VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- RLS
ALTER TABLE public.pcp_parametros_rotas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura publica de pcp_parametros_rotas" ON public.pcp_parametros_rotas;
CREATE POLICY "Permitir leitura publica de pcp_parametros_rotas"
  ON public.pcp_parametros_rotas FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Permitir insercao e edicao publica de pcp_parametros_rotas" ON public.pcp_parametros_rotas;
CREATE POLICY "Permitir insercao e edicao publica de pcp_parametros_rotas"
  ON public.pcp_parametros_rotas FOR ALL
  USING (true)
  WITH CHECK (true);
