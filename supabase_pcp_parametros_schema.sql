CREATE TABLE IF NOT EXISTS public.pcp_parametros_modal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codmodal VARCHAR(50) UNIQUE NOT NULL,
  modalidade VARCHAR(100) NOT NULL,
  descricao VARCHAR(255),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- RLS
ALTER TABLE public.pcp_parametros_modal ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura publica de pcp_parametros_modal" ON public.pcp_parametros_modal;
CREATE POLICY "Permitir leitura publica de pcp_parametros_modal"
  ON public.pcp_parametros_modal FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Permitir insercao e edicao publica de pcp_parametros_modal" ON public.pcp_parametros_modal;
CREATE POLICY "Permitir insercao e edicao publica de pcp_parametros_modal"
  ON public.pcp_parametros_modal FOR ALL
  USING (true)
  WITH CHECK (true);
