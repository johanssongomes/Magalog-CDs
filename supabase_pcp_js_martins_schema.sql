CREATE TABLE IF NOT EXISTS public.pcp_js_martins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filorig INTEGER DEFAULT 994,                      -- Filial de Origem
  codfil INTEGER DEFAULT 994,                       -- Filial
  filentrega INTEGER,                               -- Filial de Entrega (Destino)
  numlote VARCHAR(50),                              -- Lote
  fllibfat VARCHAR(10),                             -- Liberação de Faturamento (S/N)
  tpnota INTEGER,                                   -- Tipo de Nota
  numpedven VARCHAR(50),                            -- Pedido de Venda
  numpedcomp VARCHAR(50),                           -- Pedido de Compra
  dtpedido VARCHAR(50),                             -- Data do Pedido
  dtentrega VARCHAR(50),                            -- Data de Entrega
  dtlibfat VARCHAR(50),                             -- Data Liberação Faturamento
  preventrega VARCHAR(50),                          -- Previsão de Entrega
  item VARCHAR(50),                                 -- Código do Item / Produto
  ibm VARCHAR(50),                                  -- IBM / Código DF
  descricao VARCHAR(255),                           -- Descrição do Produto
  ref VARCHAR(100),                                 -- Referência do Fabricante
  fantasia VARCHAR(150),                            -- Marca / Fornecedor
  qtcomp NUMERIC(15, 2) DEFAULT 0,                  -- Quantidade Comprada
  fisico NUMERIC(15, 2) DEFAULT 0,                  -- Estoque Físico
  resfis NUMERIC(15, 2) DEFAULT 0,                  -- Reserva Física
  logico NUMERIC(15, 2) DEFAULT 0,                  -- Estoque Lógico
  reslog NUMERIC(15, 2) DEFAULT 0,                  -- Reserva de Cliente (Reslog)
  tecnico NUMERIC(15, 2) DEFAULT 0,                 -- Técnico
  futuro NUMERIC(15, 2) DEFAULT 0,                  -- Futuro
  transito NUMERIC(15, 2) DEFAULT 0,                -- Trânsito
  status VARCHAR(100),                              -- Status Geral
  situacao VARCHAR(100),                            -- Situação
  linha VARCHAR(150),                               -- Linha do Produto
  linha_ajustada VARCHAR(150),                      -- Linha Ajustada
  nucleo VARCHAR(100),                              -- Núcleo
  familia VARCHAR(100),                             -- Família
  codrota VARCHAR(50),                              -- Código da Rota
  descricaorota VARCHAR(255),                       -- Descrição da Rota
  codmodal VARCHAR(50),                             -- Código do Modal
  descricaomodal VARCHAR(150),                      -- Descrição do Modal
  status_operacao VARCHAR(100),                     -- Status da Operação (Ex: EM PROCESSO, EM CARTEIRA)
  operacao VARCHAR(100),                            -- Operação
  cub_tot NUMERIC(15, 4) DEFAULT 0,                 -- Cubagem Total (m³)
  pesoliq NUMERIC(15, 4) DEFAULT 0,                 -- Peso Líquido (kg)
  precounit NUMERIC(15, 2) DEFAULT 0,               -- Preço Unitário (R$)
  vltotal NUMERIC(15, 2) DEFAULT 0,                 -- Valor Total (R$)
  qtped NUMERIC(15, 2) DEFAULT 0,                   -- Quantidade Pedida
  dtentregaagendada VARCHAR(50),                    -- Data de Entrega Agendada
  dt_hr_libfat VARCHAR(50),                         -- Data/Hora Liberação Faturamento
  faixa_dias_reduzida VARCHAR(50),                  -- Faixa de Dias Reduzida

  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Índices estratégicos para pesquisas, filtros de planejamento e agregação
CREATE INDEX IF NOT EXISTS idx_pcp_item ON public.pcp_js_martins(item);
CREATE INDEX IF NOT EXISTS idx_pcp_filentrega ON public.pcp_js_martins(filentrega);
CREATE INDEX IF NOT EXISTS idx_pcp_status_operacao ON public.pcp_js_martins(status_operacao);
CREATE INDEX IF NOT EXISTS idx_pcp_linha ON public.pcp_js_martins(linha);
CREATE INDEX IF NOT EXISTS idx_pcp_numpedven ON public.pcp_js_martins(numpedven);

-- Habilitar RLS (Row Level Security) e permitir leitura e gravação
ALTER TABLE public.pcp_js_martins ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura publica de pcp_js_martins" ON public.pcp_js_martins;
CREATE POLICY "Permitir leitura publica de pcp_js_martins"
  ON public.pcp_js_martins FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Permitir insercao e atualizacao publica de pcp_js_martins" ON public.pcp_js_martins;
CREATE POLICY "Permitir insercao e atualizacao publica de pcp_js_martins"
  ON public.pcp_js_martins FOR ALL
  USING (true)
  WITH CHECK (true);
